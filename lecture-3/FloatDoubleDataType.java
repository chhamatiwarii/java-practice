public class FloatDoubleDataType {

    public static void main(String[] args) {
        // Float
        // when we want 5 to 6 decimal places of accuracy
        // then we will use float  (single precision)
        // Size: 4 bytes

        float f = 2.54372F;


        
        // Double
        // when we want 14 to 15 decimal places of accuracy
        // then we will use double   (double precision)
        // Size: 8 bytes

        double d = 2.437855;
    }
    
}
